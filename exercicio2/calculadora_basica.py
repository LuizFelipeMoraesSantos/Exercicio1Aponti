numero1 = input("Digite o primeiro número: ")

numero2 = input("Digite o segundo número: ")

# somar dois números
soma = (int(numero1) + int(numero2))

print(f"A soma de {numero1} + {numero2} = {soma}")

# subtrair dois números
subtracao = (int(numero1) - int(numero2))

print(f"A subtração de {numero1} - {numero2} = {subtracao}")

# multiplicar dois números
multiplicacao = (int(numero1) * int(numero2))

print(f"A multiplicação de {numero1} * {numero2} = {multiplicacao}")

# dividir dois números
divisao = (int(numero1) / int(numero2))

print(f"A divisão de {numero1} / {numero2} = {divisao}")

# media de dois números
media = (int(numero1) + int(numero2)) / 2

print(f"A média de {numero1} e {numero2} = {media}")
